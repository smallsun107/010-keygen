# --- layout ------------------------------------------------------------------
CODE_PAGE, SBOX_PAGE = 0x10019C000, 0x100B8D000
HASH_VA, AD76_VA, C5B_VA, SBOX_VA = 0x10019C330, 0x10019C610, 0x10019C630, 0x100B8D750
STRLEN_CALL, TOUPPER_CALL = 0x10019C34C, 0x10019C3C9
NAME_VA, STACK_VA, STACK_SZ, SENTINEL = 0x20000000, 0x30000000, 0x20000, 0x40000000


def _new_uc():
    mu = Uc(UC_ARCH_X86, UC_MODE_64)
    mu.mem_map(CODE_PAGE, 0x1000, UC_PROT_ALL)
    mu.mem_write(HASH_VA, HASH_CODE)
    mu.mem_write(AD76_VA, AD76_CODE)
    mu.mem_write(C5B_VA, C5B_CODE)
    mu.mem_map(SBOX_PAGE, 0x1000, UC_PROT_ALL)
    mu.mem_write(SBOX_VA, SBOX)
    mu.mem_map(NAME_VA, 0x1000, UC_PROT_ALL)
    mu.mem_map(STACK_VA, STACK_SZ, UC_PROT_ALL)
    return mu


def _run(mu, entry, regs):
    rsp = STACK_VA + STACK_SZ - 0x100
    mu.mem_write(rsp, struct.pack("<Q", SENTINEL))     # return address -> sentinel
    mu.reg_write(UC_X86_REG_RSP, rsp)
    for reg, val in regs.items():
        mu.reg_write(reg, val)

    def hook(mu, address, size, user):
        if address == SENTINEL:
            mu.emu_stop()
        elif address == STRLEN_CALL:                   # call _strlen
            p = mu.reg_read(UC_X86_REG_RDI); n = 0
            while mu.mem_read(p + n, 1)[0] != 0:
                n += 1
            mu.reg_write(UC_X86_REG_RAX, n)
            mu.reg_write(UC_X86_REG_RIP, address + 5)
        elif address == TOUPPER_CALL:                  # call ___toupper
            c = mu.reg_read(UC_X86_REG_RDI) & 0xFF
            mu.reg_write(UC_X86_REG_RAX, c - 0x20 if 0x61 <= c <= 0x7A else c)
            mu.reg_write(UC_X86_REG_RIP, address + 5)

    mu.hook_add(UC_HOOK_CODE, hook)
    mu.emu_start(entry, SENTINEL)
    return mu.reg_read(UC_X86_REG_RAX)


def emu_hash(name: bytes, flag: int, a3: int, a4: int) -> int:
    mu = _new_uc()
    mu.mem_write(NAME_VA, name + b"\x00")              # RDI = name
    return _run(mu, HASH_VA, {
        UC_X86_REG_RDI: NAME_VA, UC_X86_REG_RSI: flag,
        UC_X86_REG_RDX: a3, UC_X86_REG_RCX: a4,
    }) & 0xFFFFFFFF


def emu_ad76(x: int) -> int:
    return _run(_new_uc(), AD76_VA, {UC_X86_REG_RDI: x}) & 0xFF


def emu_c5b(x: int) -> int:
    return _run(_new_uc(), C5B_VA, {UC_X86_REG_RDI: x}) & 0xFFFF


def decode(lic: str):
    hx = lic.replace("-", "")
    return bytes(int(hx[i:i + 2], 16) for i in range(0, len(hx), 2))


def keygen_path():
    here = os.path.dirname(os.path.abspath(__file__))
    kg = os.path.join(here, "keygen")
    if not os.path.exists(kg):
        print("[*] building keygen ...")
        subprocess.check_call(["c++", "-std=c++20", "-O2", "-o", kg,
                               os.path.join(here, "main.cpp")])
    return kg


def main():
    kg = keygen_path()

    # guard: the harness itself must reproduce a known hash
    ref = emu_hash(b"smallsun", 1, 0, 230)
    print(f"[*] harness self-check  emu_hash(smallsun) = 0x{ref:08X}")
    if ref != 0xE3902F26:
        sys.exit("[!] harness self-check FAILED (embedded bytes corrupted?)")

    names = sys.argv[1:] or [
        "smallsun", "John Doe", "Alice", "Acme Corp",
        "0123456789", "a", "some long user name 123",
    ]
    bad = 0
    for name in names:
        out = subprocess.check_output([kg, "generate", name]).decode()
        lic = [l.split(": ", 1)[1] for l in out.splitlines() if l.startswith("License")][0]
        b = decode(lic)
        ver = emu_ad76(b[0] ^ b[6])
        salt = emu_c5b((b[1] ^ b[7]) << 8 | (b[2] ^ b[5]))
        h = emu_hash(name.encode(), 1, ver if ver < 2 else 0, salt)
        stored = b[4] | (b[5] << 8) | (b[6] << 16) | (b[7] << 24)
        ok = (ver >= 17 and 1 <= salt <= 1000 and b[3] == 0x9C and h == stored)
        print(f"{'PASS' if ok else 'FAIL'}  {name!r:24} {lic}  ver={ver} salt={salt} hash=0x{h:08X}")
        if not ok:
            bad += 1
    print(f"\n{len(names) - bad}/{len(names)} passed" + ("  [OK]" if bad == 0 else "  [FAIL]"))
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
